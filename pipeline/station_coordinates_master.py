# 按鍵名長度降序排序，確保長字（最精確專有名詞）優先匹配
SORTED_KEYS = sorted(STATION_COORDINATES_DB.keys(), key=lambda k: len(k), reverse=True)

def resolve_station_coords(raw_name: str, fallback_lat: float = None, fallback_lon: float = None) -> list:
    """
    階層式精確解析站點經緯度
    1. 完全一致匹配 (Exact Match)
    2. 清理前綴/尾綴後完全匹配 (Clean Exact Match)
    3. 最長前綴/子字串匹配 (Longest Prefix Match，受保護單詞排除)
    """
    if not raw_name or raw_name == '-99':
        return [25.0478, 121.5170]
        
    name = raw_name.strip()
    
    # 1. 完全一致
    if name in STATION_COORDINATES_DB:
        return STATION_COORDINATES_DB[name]
        
    # 2. 清理正規化後比對
    clean = (
        name.replace("YouBike2.0_", "")
            .replace("捷運", "")
            .replace("火車站", "")
            .replace("車站", "")
            .replace("轉運站", "")
            .replace("(O)", "")
            .strip()
    )
    if clean in STATION_COORDINATES_DB:
        return STATION_COORDINATES_DB[clean]
        
    # 嘗試加上「捷運」或「站」
    if f"捷運{clean}站" in STATION_COORDINATES_DB:
        return STATION_COORDINATES_DB[f"捷運{clean}站"]
    if f"{clean}站" in STATION_COORDINATES_DB:
        return STATION_COORDINATES_DB[f"{clean}站"]
    if f"{clean}火車站" in STATION_COORDINATES_DB:
        return STATION_COORDINATES_DB[f"{clean}火車站"]
        
    # 3. 最長匹配（長字優先，避免短字覆蓋）
    for k in SORTED_KEYS:
        # 檢查保護條款
        violates_protection = False
        for generic, specific_list in PROTECTED_PREFIXES.items():
            if k == generic and any(spec in name for spec in specific_list):
                violates_protection = True
                break
        if violates_protection:
            continue
            
        if len(k) >= 3 and (k in name or name in k):
            return STATION_COORDINATES_DB[k]
        elif len(k) == 2 and k == clean:
            return STATION_COORDINATES_DB[k]

    if fallback_lat is not None and fallback_lon is not None:
        return [fallback_lat, fallback_lon]
        
    # 若依然無解，預設雙北都會中心
    return [25.0478, 121.5170]

def resolve_station_region(name: str, lat: float, lon: float) -> str:
    """
    依據精確地理經緯度與特定行政區判定所屬生活圈
    徹底修正將台北「成功國宅」判成東部、將「深坑」「台電大樓」判成南部的問題！
    """
    # 1. 宜花東 (東部生活圈)
    # 東部特徵：經度大於 121.3 且緯度在 22.4 ~ 24.8 之間 (中央山脈以東)
    if any(k in name for k in ['羅東', '宜蘭', '礁溪', '花蓮', '台東', '臺東', '太麻里', '知本', '蘇澳', '玉里']):
        return 'East'
    if lon >= 121.55 and lat <= 24.85 and lat >= 22.4:
        # 檢查是否為雙北（雙北在 24.95 ~ 25.3 之間，即便在東側也是北部）
        if lat < 24.90:
            return 'East'

    # 2. 依緯度劃分西半部
    if lat >= 24.75:
        # 基隆、台北、新北、桃園、新竹
        return 'North'
    elif 23.50 <= lat < 24.75:
        # 苗栗、台中、彰化、南投、雲林
        return 'Central'
    else:
        # 嘉義、台南、高雄、屏東
        return 'South'

def apply_polar_jitter(lat: float, lon: float, index: int, total: int, radius_meters: float = 35.0) -> list:
    """
    為共構/完全同座標的站點施加微幅極座標發散偏移 (Polar Jitter)
    使多個站點在地圖放大時能清晰分辨且不會 100% 重疊遮蔽
    """
    if total <= 1:
        return [round(lat, 5), round(lon, 5)]
        
    angle = (2.0 * math.pi * index) / total
    # 1 度緯度約 111,000 公尺，1 度經度在台灣約 102,000 公尺
    d_lat = (radius_meters * math.cos(angle)) / 111000.0
    d_lon = (radius_meters * math.sin(angle)) / 102000.0
    return [round(lat + d_lat, 5), round(lon + d_lon, 5)]
